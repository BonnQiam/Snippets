int nextHigher(int x){    
    int a, b, c, d = 0;

    if (x){
        a = x & -(signed)x;
        b = x + a;
        c = (x ^ b) / a;       
        c >>= 2;
        d = b | c;
    }
    
    return d;
}

/*
这段代码的目的是找到一个整数x的下一个更大的数，这个数与x有相同数量的二进制位为1。这个算法的步骤如下：

1. 初始化变量：a, b, c, d都被初始化为0。其中d将作为函数的返回值。

2. 检查x是否非零：如果x为0，则函数直接返回0，因为0的下一个更大的数也是0。

3. 计算 a：a = x & -(signed)x;。这一步是计算 x的最低位的 1的位置。-(signed)x是 x 的二进制补码，与 x 进行与操作得到的是 x 中最低位的 1 及其后的所有0。

4.计算 b：b = x + a;。这一步是将x加上a，由于a是x中最低位的 1及其后的所有0，加上a相当于将x的最低位的1向左移动了一位，同时保持了x中其他1的位置不变。

5. 计算 c：c = (x ^ b) / a;。首先，x ^ b计算x与b的异或，这将会清除x和b中相同的位。由于b是x加上a，这一步实际上是找到x中除了最低位的1之外的所有1。然后，除以a是为了将这些1右移两位。

6. 右移 c：c >>= 2;。这一步是将上一步得到的结果再右移两位，目的是为了在最终的结果中为原来x中的最低位的1腾出位置。

7. 计算 d：d = b | c;。这一步是将b和c进行或操作，将x的最低位的1向左移动后，再将x中其他的1按照一定的规则重新排列，得到最终的结果。

返回结果：函数返回d，即下一个更大的数，这个数与x有相同数量的二进制位为1。
*/